-- ============================================================================
-- UROO.Admin — Supabase schema
-- Mirror of the Laravel (MySQL) tables used by the mobile app, using BIGINT
-- primary keys so IDs & FKs are identical on both sides for seamless 2-way
-- sync. RLS restricts rows by auth.uid() via users.supabase_uid.
--
-- Run this in the Supabase SQL editor. Then enable Realtime when desired.
-- ============================================================================

-- ----------------------------------------------------------------------------
-- 1. users (bigint PK, links to auth.users via supabase_uid uuid)
-- ----------------------------------------------------------------------------
create table if not exists public.users (
  id              bigint generated by default as identity primary key,
  name            text not null,
  email           text not null unique,
  email_verified_at timestamptz,
  password        text,                 -- nullable (mobile uses Supabase Auth)
  remember_token  text,
  supabase_uid    uuid unique,
  created_at      timestamptz default now(),
  updated_at      timestamptz default now()
);

-- Keep updated_at fresh for sync watermarks
create or replace function public.set_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end $$;

-- Create users row automatically when a Supabase Auth user signs up
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.users (name, email, supabase_uid)
  values (
    coalesce(new.raw_user_meta_data ->> 'name', split_part(new.email, '@', 1)),
    new.email,
    new.id
  )
  on conflict (supabase_uid) do nothing;
  return new;
end $$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- Security: allow the authenticated app to read its own row
create policy "users own row"
  on public.users for select
  using (supabase_uid = auth.uid());

