-- ----------------------------------------------------------------------------
-- 3. updated_at triggers
-- ----------------------------------------------------------------------------
do $$
declare t text;
begin
  foreach t in array array[
    'public.users','public.clients','public.projects','public.invoices',
    'public.invoice_payments','public.app_ideas','public.brain_dumps',
    'public.notes','public.savings_goals','public.savings_transactions',
    'public.repositories','public.commits','public.subscriptions'
  ] loop
    execute format(
      'drop trigger if exists trg_set_updated_at on %I.%I',
      split_part(t, '.', 1), split_part(t, '.', 2));
    execute format(
      'create trigger trg_set_updated_at before update on %I.%I
       for each row execute function public.set_updated_at()',
      split_part(t, '.', 1), split_part(t, '.', 2));
  end loop;
end $$;

-- ----------------------------------------------------------------------------
-- 4. Row Level Security
-- ----------------------------------------------------------------------------

-- Helper: return the user's integer id for the current auth.uid()
create or replace function public.current_user_id()
returns bigint language sql stable security definer set search_path = public as $$
  select id from public.users where supabase_uid = auth.uid();
$$;

do $$
declare tables text[] := array[
  'clients','projects','invoices','app_ideas',
  'brain_dumps','notes','savings_goals',
  'repositories','subscriptions'
];
declare t text;
begin
  foreach t in array tables loop
    execute format('alter table public.%I enable row level security;', t);
    execute format('drop policy if exists "own rows on %I" on public.%I;', t, t);
    execute format($p$
      create policy "own rows on %I" on public.%I
      for all
      using (user_id = public.current_user_id())
      with check (user_id = public.current_user_id()) $p$, t, t);
  end loop;
end $$;

-- RLS for rows that only have a parent (no direct user_id): guard through
-- the parent's user_id instead.
alter table public.invoice_payments enable row level security;
drop policy if exists "own invoice payments" on public.invoice_payments;
create policy "own invoice payments" on public.invoice_payments
  for all
  using (
    exists (select 1 from public.invoices i
            where i.id = invoice_payments.invoice_id
              and i.user_id = public.current_user_id())
  )
  with check (
    exists (select 1 from public.invoices i
            where i.id = invoice_payments.invoice_id
              and i.user_id = public.current_user_id())
  );

alter table public.savings_transactions enable row level security;
drop policy if exists "own savings transactions" on public.savings_transactions;
create policy "own savings transactions" on public.savings_transactions
  for all
  using (
    exists (select 1 from public.savings_goals g
            where g.id = savings_transactions.goal_id
              and g.user_id = public.current_user_id())
  )
  with check (
    exists (select 1 from public.savings_goals g
            where g.id = savings_transactions.goal_id
              and g.user_id = public.current_user_id())
  );

alter table public.commits enable row level security;
drop policy if exists "own commits" on public.commits;
create policy "own commits" on public.commits
  for all
  using (
    exists (select 1 from public.repositories r
            where r.id = commits.repository_id
              and r.user_id = public.current_user_id())
  )
  with check (
    exists (select 1 from public.repositories r
            where r.id = commits.repository_id
              and r.user_id = public.current_user_id())
  );

